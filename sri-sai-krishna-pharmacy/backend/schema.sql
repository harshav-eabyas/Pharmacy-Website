USE SriSaiPharmacy;
GO
CREATE TABLE Roles(Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(30) UNIQUE NOT NULL);
CREATE TABLE Users(Id INT IDENTITY PRIMARY KEY, Username NVARCHAR(50) UNIQUE NOT NULL, PasswordHash NVARCHAR(200) NOT NULL,
  FullName NVARCHAR(100), RoleId INT NOT NULL REFERENCES Roles(Id), IsActive BIT DEFAULT 1);
CREATE TABLE Categories(Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(80) NOT NULL);
CREATE TABLE Medicines(Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(150) NOT NULL, GenericName NVARCHAR(150),
  CategoryId INT REFERENCES Categories(Id), Manufacturer NVARCHAR(120), Mrp DECIMAL(10,2) NOT NULL,
  GstPercent DECIMAL(5,2) DEFAULT 12, ReorderLevel INT DEFAULT 10, IsActive BIT DEFAULT 1);
CREATE TABLE MedicineBatches(Id INT IDENTITY PRIMARY KEY, MedicineId INT NOT NULL REFERENCES Medicines(Id),
  BatchNo NVARCHAR(50) NOT NULL, ExpiryDate DATE NOT NULL, PurchasePrice DECIMAL(10,2), Quantity INT NOT NULL);
CREATE TABLE Customers(Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(100) NOT NULL, Phone NVARCHAR(20), Email NVARCHAR(120), Address NVARCHAR(250));
CREATE TABLE Suppliers(Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(120) NOT NULL, Phone NVARCHAR(20), Email NVARCHAR(120), Address NVARCHAR(250));
CREATE TABLE PurchaseOrders(Id INT IDENTITY PRIMARY KEY, SupplierId INT REFERENCES Suppliers(Id), OrderDate DATETIME DEFAULT GETDATE(), Status NVARCHAR(20) DEFAULT 'Pending', Total DECIMAL(12,2));
CREATE TABLE PurchaseOrderItems(Id INT IDENTITY PRIMARY KEY, PurchaseOrderId INT REFERENCES PurchaseOrders(Id), MedicineId INT REFERENCES Medicines(Id), Quantity INT, UnitPrice DECIMAL(10,2));
CREATE TABLE Sales(Id INT IDENTITY PRIMARY KEY, CustomerId INT NULL REFERENCES Customers(Id), SoldBy INT REFERENCES Users(Id),
  SaleDate DATETIME DEFAULT GETDATE(), Discount DECIMAL(10,2) DEFAULT 0, Total DECIMAL(12,2), Status NVARCHAR(20) DEFAULT 'Completed');
CREATE TABLE SaleItems(Id INT IDENTITY PRIMARY KEY, SaleId INT REFERENCES Sales(Id), MedicineId INT REFERENCES Medicines(Id),
  BatchId INT REFERENCES MedicineBatches(Id), Quantity INT, UnitPrice DECIMAL(10,2));
CREATE TABLE Inquiries(Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(100), Email NVARCHAR(120), Phone NVARCHAR(20), Subject NVARCHAR(150), Message NVARCHAR(2000), CreatedAt DATETIME DEFAULT GETDATE());
CREATE TABLE AuditLogs(Id INT IDENTITY PRIMARY KEY, UserId INT, Action NVARCHAR(200), CreatedAt DATETIME DEFAULT GETDATE());
